def generate_gallup_questions():
    # Нам нужно 177 пар.
    # Мы случайным образом будем брать 2 разные темы и по одному утверждению из них.
    themes_list = list(gallup_data.keys())
    
    questions = []
    
    # Чтобы распределение было равномерным, будем вести учет использований каждой темы
    theme_usage = {t: 0 for t in themes_list}
    
    # Генерируем 177 пар
    for i in range(1, 178):
        # Выбираем две наименее использованные темы для баланса
        sorted_themes = sorted(themes_list, key=lambda t: theme_usage[t] + random.random())
        theme_a = sorted_themes[0]
        
        # Для второй темы берем одну из следующих наименее использованных
        # Но добавим немного случайности, чтобы не было предсказуемости
        theme_b = sorted_themes[random.randint(1, 4)]
        
        # Обновляем счетчики
        theme_usage[theme_a] += 1
        theme_usage[theme_b] += 1
        
        # Выбираем случайное утверждение из выбранных тем
        statement_a = random.choice(gallup_data[theme_a])
        statement_b = random.choice(gallup_data[theme_b])
        
        questions.append({
            "id": i,
            "statement_a": statement_a,
            "statement_b": statement_b,
            "theme_a": theme_a,
            "theme_b": theme_b
        })
        
    return questions

if __name__ == "__main__":
    # Устанавливаем seed для воспроизводимости, чтобы при пересоздании вопросы были теми же
    random.seed(42)
    
    questions = generate_gallup_questions()
    
    output_path = os.path.join(os.path.dirname(__file__), 'gallup_questions.json')
    with open(output_path, 'w', encoding='utf-8') as f:
        json.dump(questions, f, ensure_ascii=False, indent=2)
        
    print(f"✅ Успешно сгенерировано 177 вопросов. Файл сохранен: {output_path}")
    
    # Проверка распределения
    theme_counts = {}
    for q in questions:
        theme_counts[q['theme_a']] = theme_counts.get(q['theme_a'], 0) + 1
        theme_counts[q['theme_b']] = theme_counts.get(q['theme_b'], 0) + 1
    
    print("\nСтатистика распределения тем в вопросах:")
    min_uses = min(theme_counts.values())
    max_uses = max(theme_counts.values())
    print(f"Каждая из 34 тем встречается от {min_uses} до {max_uses} раз.")
